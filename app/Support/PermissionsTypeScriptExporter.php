<?php

namespace App\Support;

use App\Enums\PermissionName;
use App\Enums\RoleName;
use Illuminate\Support\Str;

/**
 * Renders the roles and permissions defined by the PHP enums (the source of
 * truth the seeder uses) as a TypeScript module for the front end.
 *
 * Permissions are grouped by resource, using the part of the name before the
 * first dot, e.g. `requests.index` -> `Requests.index`.
 */
class PermissionsTypeScriptExporter
{
    public function render(): string
    {
        $roles = collect(RoleName::cases())
            ->map(fn (RoleName $role) => "    {$role->name}: '{$role->value}',")
            ->implode("\n");

        $groups = $this->groups()
            ->map(function (array $permissions, string $group) {
                $lines = collect($permissions)
                    ->map(fn (string $value, string $key) => "    {$key}: '{$value}',")
                    ->implode("\n");

                return "export const {$group} = {\n{$lines}\n} as const;";
            })
            ->implode("\n\n");

        $union = $this->groups()
            ->keys()
            ->map(fn (string $group) => "(typeof {$group})[keyof typeof {$group}]")
            ->implode(' | ');

        return <<<TS
        // This file is auto-generated by `php artisan permissions:export-ts`.
        // Do not edit it by hand: change the PHP enums and run the command again.

        export const Role = {
        {$roles}
        } as const;

        export type Role = (typeof Role)[keyof typeof Role];

        {$groups}

        export type Permission = {$union};

        TS;
    }

    /**
     * @return \Illuminate\Support\Collection<string, array<string, string>>
     */
    private function groups()
    {
        return collect(PermissionName::cases())
            ->groupBy(fn (PermissionName $p) => $this->group($p))
            ->map(fn ($permissions) => $permissions
                ->mapWithKeys(fn (PermissionName $p) => [$this->key($p) => $p->value])
                ->sortKeys()
                ->all())
            ->sortKeys();
    }

    private function group(PermissionName $permission): string
    {
        return Str::studly(Str::before($permission->value, '.'));
    }

    private function key(PermissionName $permission): string
    {
        return Str::camel(Str::after($permission->value, '.'));
    }
}
